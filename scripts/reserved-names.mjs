#!/usr/bin/env node
// Every skill and agent name `rein` provisions, read from a rein release tree
// (.ai/blueprints/language-packs.md §Data Model: CI holds the list as scripts/reserved-names.json,
// taken from the pinned rein release the publish scan uses). A pack skill must not take one.
//
//   node scripts/reserved-names.mjs <rein-tree> <release>            print the JSON
//   node scripts/reserved-names.mjs <rein-tree> <release> --check    exit 1 with [PACK_RESERVED_DRIFT]
//                                                                    when scripts/reserved-names.json differs
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const [tree, release, flag] = process.argv.slice(2);
if (!tree || !release) { console.error("usage: node scripts/reserved-names.mjs <rein-tree> <release> [--check]"); process.exit(1); }
const fmName = (f) => /^---\r?\n[\s\S]*?^name:\s*["']?([^"'\r\n]+?)["']?\s*$/m.exec(readFileSync(f, "utf8"))?.[1];
const names = new Set();
for (const d of ["src/claude/skills", "src/shared/skills"]) {
  const base = join(tree, d);
  if (!existsSync(base)) continue;
  for (const s of readdirSync(base)) {
    const f = join(base, s, "SKILL.md");
    if (statSync(join(base, s)).isDirectory() && existsSync(f)) names.add(fmName(f) || s);
  }
}
const agents = join(tree, "src/claude/agents");
if (existsSync(agents)) for (const f of readdirSync(agents).filter((n) => n.endsWith(".md"))) names.add(fmName(join(agents, f)) || basename(f, ".md"));
if (names.size === 0) { console.error(`[PACK_RESERVED_EMPTY] no skill or agent found under ${tree} — not a rein tree?`); process.exit(1); }

const doc = { _comment: "Skill and agent names rein provisions; generated by scripts/reserved-names.mjs from the pinned rein release. Do not edit by hand.", release, names: [...names].sort() };
const text = `${JSON.stringify(doc, null, 2)}\n`;
if (flag !== "--check") { process.stdout.write(text); process.exit(0); }
const file = join(resolve(dirname(fileURLToPath(import.meta.url))), "reserved-names.json");
if (!existsSync(file) || readFileSync(file, "utf8") !== text) {
  console.error(`[PACK_RESERVED_DRIFT] scripts/reserved-names.json does not match rein ${release} — regenerate: node scripts/reserved-names.mjs <rein-tree> ${release} > scripts/reserved-names.json`);
  process.exit(1);
}
console.log(`[PACK_RESERVED_OK] ${doc.names.length} names from rein ${release}`);
